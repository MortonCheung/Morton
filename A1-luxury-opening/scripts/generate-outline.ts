/**
 * Offline outline generator — the construction lines that the opening draws.
 *
 *   npm run gen:outline
 *
 * Why offline: the SVG construction lines must be available on the very first
 * frame (so the drawing never waits for a network resource), while the solid
 * letters still wait for the real TTF. Generating the paths from the same
 * `parseWord` + `layoutWord` code that runtime geometry uses is what guarantees
 * the line art and the extruded letters share a layout instead of "matching
 * approximately".
 *
 * Output: src/data/outline.generated.ts (committed; regenerate when WORD /
 * TRACKING / the font file changes).
 */
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { contourArea, contourPoints, contourToPath, layoutWord, parseWord } from '../src/letters/font.ts'
import { EM_SIZE, TRACKING, WORD } from '../src/data/wordSpec.ts'
import type { OutlineContour, WordOutlineData } from '../src/types/opening.ts'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '..')
const fontPath = resolve(root, 'public/fonts/marcellus.ttf')
const outPath = resolve(root, 'src/data/outline.generated.ts')

const bytes = readFileSync(fontPath)
const buffer = bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength) as ArrayBuffer
const sha = createHash('sha256').update(bytes).digest('hex')

const outline = parseWord(buffer, WORD, EM_SIZE, TRACKING)
const layout = layoutWord(outline)

let minX = Infinity
let maxX = -Infinity
let minY = Infinity
let maxY = -Infinity

const letters = layout.letters.map((placed, index) => {
  const source = outline.letters[index]
  const contours: OutlineContour[] = source.contours
    .map((c) => {
      const pts = contourPoints(c, 48)
      for (const p of pts) {
        minX = Math.min(minX, p.x + placed.offsetX)
        maxX = Math.max(maxX, p.x + placed.offsetX)
        minY = Math.min(minY, p.y)
        maxY = Math.max(maxY, p.y)
      }
      return { d: contourToPath(c), area: Number(Math.abs(contourArea(c)).toFixed(6)) }
    })
    // outer contour first, its counters afterwards — reads as real construction
    .sort((a, b) => b.area - a.area)

  return {
    id: `${source.char}-${index}`,
    char: source.char,
    index,
    offsetX: Number(placed.offsetX.toFixed(6)),
    advance: Number(placed.advance.toFixed(6)),
    contours,
  }
})

const data: WordOutlineData = {
  word: WORD,
  emSize: EM_SIZE,
  tracking: TRACKING,
  width: Number(layout.width.toFixed(6)),
  ink: {
    minX: Number(minX.toFixed(6)),
    maxX: Number(maxX.toFixed(6)),
    minY: Number(minY.toFixed(6)),
    maxY: Number(maxY.toFixed(6)),
  },
  centerY: Number(((minY + maxY) / 2).toFixed(6)),
  capHeight: Number(outline.capHeight.toFixed(6)),
  letters,
}

const header = `// AUTO-GENERATED by scripts/generate-outline.ts — do not edit by hand.
// Source font: public/fonts/marcellus.ttf (Marcellus, SIL OFL 1.1)
// sha256 ${sha}
// Regenerate with: npm run gen:outline
import type { WordOutlineData } from '../types/opening'

export const OUTLINE: WordOutlineData = ${JSON.stringify(data, null, 2)}
`

writeFileSync(outPath, header)
console.log(
  `[outline] ${WORD} · ${letters.length} letters · ink ${(maxX - minX).toFixed(3)} × ${(maxY - minY).toFixed(3)} em · cap ${outline.capHeight.toFixed(3)} · contours ${letters.reduce((n, l) => n + l.contours.length, 0)}`,
)
console.log(`[outline] wrote ${outPath}`)
